#!/bin/bash
# 全链路回归：按报告附录 A 的顺序重跑全部步骤，任何一步失败即中止
set -e
cd "$(dirname "$0")/.."
PY="$HOME/.workbuddy/binaries/python/envs/default/Scripts/python.exe"
A="20-分析"
L="90-归档"

echo "############ [1/13] 03 核心计算 ############"
"$PY" "$A/03_细胞类型年龄谱.py"        > "$L/03核心计算日志.txt" 2>&1
tail -3 "$L/03核心计算日志.txt"

echo "############ [2/13] 04 无监督 ############"
"$PY" "$A/04_无监督分析.py"              > "$L/04无监督分析日志.txt" 2>&1
tail -3 "$L/04无监督分析日志.txt"

echo "############ [3/13] 05 A 全量 ############"
"$PY" "$A/05_监督分析.py"                > "$L/05监督分析日志.txt" 2>&1
tail -3 "$L/05监督分析日志.txt"

echo "############ [4/13] 05 B 共识度过滤 ############"
# ⚠️ 参数是 --min-share（共识度 mode_share ≥ 0.8），**不是 --min-dbs**。
#    NumDBsContributing 是分母不是支持数，按 n_dbs 过滤方向是反的。
"$PY" "$A/05_监督分析.py" --min-share 0.8 --tag confident > "$L/05监督分析日志_confident.txt" 2>&1
tail -3 "$L/05监督分析日志_confident.txt"

echo "############ [5/13] 05 C 短蛋白剔除 ############"
"$PY" "$A/05_监督分析.py" --min-length 100 --tag shortprot > "$L/05监督分析日志_shortprot.txt" 2>&1
tail -3 "$L/05监督分析日志_shortprot.txt"

echo "############ [6/13] 06 三次稳健性对照 ############"
"$PY" "$A/06_稳健性对比.py"              > "$L/06稳健性对比日志.txt" 2>&1
tail -5 "$L/06稳健性对比日志.txt"

echo "############ [7/13] 08 主成分诊断 ############"
"$PY" "$A/08_主成分诊断.py"              > "$L/08主成分诊断日志.txt" 2>&1
tail -4 "$L/08主成分诊断日志.txt"

echo "############ [8/13] 06 画图 ############"
"$PY" "30-可视化/06_画图.py" --all       > "$L/06画图日志.txt" 2>&1
tail -3 "$L/06画图日志.txt"

echo "############ [9/13] 07 做网页 ############"
"$PY" "30-可视化/07_做网页.py"           > "$L/07做网页日志.txt" 2>&1
tail -3 "$L/07做网页日志.txt"

echo "############ [10/13] 03 检验 D：长蛋白版 TAI ############"
"$PY" "$A/03_细胞类型年龄谱.py" --min-length 100 --tag longprot \
      > "$L/03核心计算日志_longprot.txt" 2>&1
tail -3 "$L/03核心计算日志_longprot.txt"

echo "############ [11/13] 94 长蛋白对照 ############"
"$PY" "$A/94_长蛋白对照.py"                > "$L/94长蛋白对照日志.txt" 2>&1
tail -3 "$L/94长蛋白对照日志.txt"

echo "############ [12/13] 07 报告终审核对（必须全过）############"
"$PY" "$A/07_终审核对.py"

echo "############ [13/13] 95 论文数字终审（必须全过）############"
"$PY" "$A/95_论文数字终审.py"

echo "############ 回归完成 ############"
